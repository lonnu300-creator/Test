import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const androidDir = path.join(root, 'android');
const appDir = path.join(androidDir, 'app');
const resSource = path.join(root, 'android-resources', 'res');
const resTarget = path.join(appDir, 'src', 'main', 'res');

function fail(message) {
  console.error(`Farnava Android preparation failed: ${message}`);
  process.exit(1);
}
function replaceRequired(text, regex, replacement, label) {
  if (!regex.test(text)) fail(`Could not find ${label} in generated Android project.`);
  return text.replace(regex, replacement);
}
function copyTree(source, target) {
  if (!fs.existsSync(source)) fail(`Android resource directory is missing: ${source}`);
  fs.mkdirSync(target, { recursive: true });
  for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
    const from = path.join(source, entry.name);
    const to = path.join(target, entry.name);
    if (entry.isDirectory()) copyTree(from, to);
    else fs.copyFileSync(from, to);
  }
}

if (!fs.existsSync(path.join(appDir, 'build.gradle'))) {
  fail('android/app/build.gradle was not generated by Capacitor.');
}

copyTree(resSource, resTarget);

const stringsPath = path.join(resTarget, 'values', 'strings.xml');
fs.mkdirSync(path.dirname(stringsPath), { recursive: true });
if (fs.existsSync(stringsPath)) {
  let strings = fs.readFileSync(stringsPath, 'utf8');
  if (/<string\s+name="app_name">[\s\S]*?<\/string>/.test(strings)) {
    strings = strings.replace(/<string\s+name="app_name">[\s\S]*?<\/string>/, '<string name="app_name">فرنوا</string>');
  } else {
    strings = strings.replace('</resources>', '    <string name="app_name">فرنوا</string>\n</resources>');
  }
  fs.writeFileSync(stringsPath, strings);
} else {
  fs.writeFileSync(stringsPath, '<?xml version="1.0" encoding="utf-8"?>\n<resources><string name="app_name">فرنوا</string></resources>\n');
}

const variablesPath = path.join(androidDir, 'variables.gradle');
if (fs.existsSync(variablesPath)) {
  let variables = fs.readFileSync(variablesPath, 'utf8');
  variables = replaceRequired(variables, /(minSdkVersion\s*=\s*)\d+/, '$123', 'minSdkVersion');
  variables = replaceRequired(variables, /(compileSdkVersion\s*=\s*)\d+/, '$136', 'compileSdkVersion');
  variables = replaceRequired(variables, /(targetSdkVersion\s*=\s*)\d+/, '$136', 'targetSdkVersion');
  fs.writeFileSync(variablesPath, variables);
}

const gradlePath = path.join(appDir, 'build.gradle');
let gradle = fs.readFileSync(gradlePath, 'utf8');
gradle = replaceRequired(gradle, /versionCode\s+\d+/, 'versionCode 1', 'versionCode');
gradle = replaceRequired(gradle, /versionName\s+["'][^"']+["']/, 'versionName "1.0.0"', 'versionName');
if (!/applicationId\s+["']ir\.farnava\.app["']/.test(gradle)) {
  console.warn('Note: applicationId differs from ir.farnava.app; keeping the generated applicationId unchanged.');
}
fs.writeFileSync(gradlePath, gradle);

const manifestPath = path.join(appDir, 'src', 'main', 'AndroidManifest.xml');
if (fs.existsSync(manifestPath)) {
  let manifest = fs.readFileSync(manifestPath, 'utf8');
  if (!/android:label=/.test(manifest)) {
    manifest = manifest.replace(/<application\b/, '<application android:label="@string/app_name"');
  } else {
    manifest = manifest.replace(/android:label="[^"]*"/, 'android:label="@string/app_name"');
  }
  if (!/android:roundIcon=/.test(manifest)) {
    manifest = manifest.replace(/android:icon="[^"]*"/, 'android:icon="@mipmap/ic_launcher" android:roundIcon="@mipmap/ic_launcher_round"');
  }
  fs.writeFileSync(manifestPath, manifest);
}

console.log('Farnava Android app name, version, SDK levels and launcher icons are prepared.');
